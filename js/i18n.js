window.eugreenDetectLang = function () {
  const saved = localStorage.getItem("eugreen-lang");
  if (saved && T[saved]) return saved;
  const nav = (navigator.language || "de").toLowerCase();
  const primary = nav.split("-")[0];
  const region = (nav.split("-")[1] || "").toUpperCase();
  const regionMap = { AT: "de", CH: "de", BE: "nl", LU: "fr", IE: "en", GB: "en", UK: "en", GR: "el", CY: "el" };
  if (regionMap[region] && T[regionMap[region]]) return regionMap[region];
  if (T[primary]) return primary;
  return "en";
};
